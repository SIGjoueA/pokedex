import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox'] });
const p = await b.newPage();
await p.emulateMediaFeatures([{ name: 'prefers-color-scheme', value: 'dark' }]);
await p.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true });
await p.goto('http://localhost:8765/', { waitUntil: 'networkidle0' });
await p.click('#viewbtn');
await p.screenshot({ path: 'shot-dark-list.png' });
await p.goto('http://localhost:8765/#/p/6'); await new Promise(r => setTimeout(r, 600));
await p.screenshot({ path: 'shot-dark-detail.png' });
await p.setViewport({ width: 1280, height: 800 }); await p.goto('http://localhost:8765/#/'); await new Promise(r => setTimeout(r, 600));
await p.screenshot({ path: 'shot-desktop.png' });
await b.close();
