import puppeteer from 'puppeteer-core';
const URL = 'http://localhost:8765/';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox'] });
const p = await b.newPage();
await p.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
await p.goto(URL, { waitUntil: 'networkidle0' });
const count = () => p.$eval('#count', e => e.textContent);
const names = () => p.$$eval('.card .nm', es => es.slice(0, 5).map(e => e.textContent.trim()));
console.log('initial', await count());
const search = async q => { await p.$eval('#q', e => e.value = ''); await p.type('#q', q); return [await count(), await names()]; };
for (const q of ['pika', 'evoli', 'Évoli', 'flabebe', '25', '#150', 'mime', 'nidoran', 'gastly']) console.log(q, JSON.stringify(await search(q)));
await p.$eval('#q', e => { e.value = ''; e.dispatchEvent(new Event('input')); });
await p.select('#gen', '3'); console.log('gen3', await count());
await p.click('[data-t=fire]'); console.log('gen3+fire', await count(), await names());
await p.click('[data-t=flying]'); console.log('gen3+fire+flying', await count(), await names());
await p.click('#reset'); console.log('reset', await count());
await p.screenshot({ path: '/workspace/pokedex/build/shot-list.png' });
await p.goto(URL + '#/p/92'); await new Promise(r => setTimeout(r, 800));
await p.screenshot({ path: '/workspace/pokedex/build/shot-detail.png', fullPage: true });
await p.goto(URL + '#/p/133'); await new Promise(r => setTimeout(r, 800));
await p.screenshot({ path: '/workspace/pokedex/build/shot-evo.png', fullPage: true });
// SW + offline
await p.goto(URL); await p.evaluate(() => navigator.serviceWorker.ready);
await new Promise(r => setTimeout(r, 8000));
console.log('imgsDone', await p.evaluate(() => localStorage.getItem('imgsDone')), 'cache keys', await p.evaluate(async () => (await (await caches.open('pokedex-img')).keys()).length));
await p.setOfflineMode(true);
await p.reload({ waitUntil: 'load' });
await new Promise(r => setTimeout(r, 1500));
console.log('offline count', await count(), await search('dracaufeu'));
await p.goto(URL + '#/p/6'); await new Promise(r => setTimeout(r, 500));
console.log('offline detail', await p.$eval('h1', e => e.textContent), await p.$$eval('.evpk img', is => is.every(i => i.complete && i.naturalWidth > 0)));
console.log('errors', errs);
await b.close();
